"""
document_builder.py
Build a translated document from TranslationSegment objects.
Supports TXT and DOCX output formats.
"""
import io
from typing import List


def build_translated_document(
    segments: List,
    out_format: str,
    source_lang: str,
    target_lang: str,
) -> tuple[bytes, str]:
    """
    Build a translated document from TranslationSegment objects.
    Returns (file_bytes, content_type).
    out_format: 'txt' or 'docx'
    """
    if out_format == "docx":
        return _build_docx(segments, source_lang, target_lang)
    return _build_txt(segments, source_lang, target_lang)


def _build_txt(segments: List, source_lang: str, target_lang: str) -> tuple[bytes, str]:
    """
    Build a plain-text file preserving structure and paragraph order.
    Blank translated segments are labelled [NEEDS TRANSLATION].
    """
    lines: list[str] = []
    lines.append(f"Translated from {source_lang} to {target_lang}")
    lines.append("Generated by SYNORA IndicTranslate · Machine translation draft · Human review required")
    lines.append("")

    i = 0
    n = len(segments)
    while i < n:
        seg = segments[i]
        b_type = getattr(seg, "blockType", None) or "paragraph"
        translated = (seg.translated or "").strip()
        if not translated:
            excerpt = seg.source[:80]
            ellipsis = "..." if len(seg.source) > 80 else ""
            translated = f"[NEEDS TRANSLATION: {excerpt}{ellipsis}]"

        if b_type == "heading":
            lines.append(f"# {translated}")
            lines.append("")
            i += 1
        elif b_type == "bullet":
            lines.append(f"• {translated}")
            lines.append("")
            i += 1
        elif b_type == "table_cell":
            tbl_idx = getattr(seg, "tableIndex", None)
            table_segs = []
            while i < n:
                curr_seg = segments[i]
                curr_type = getattr(curr_seg, "blockType", None)
                curr_tbl_idx = getattr(curr_seg, "tableIndex", None)
                if curr_type == "table_cell" and curr_tbl_idx == tbl_idx:
                    table_segs.append(curr_seg)
                    i += 1
                else:
                    break

            num_rows = max((s.rowIndex or 0) for s in table_segs) + 1
            num_cols = max((s.cellIndex or 0) for s in table_segs) + 1
            grid = [["" for _ in range(num_cols)] for _ in range(num_rows)]
            for s in table_segs:
                r = s.rowIndex or 0
                c = s.cellIndex or 0
                t_val = (s.translated or "").strip() or f"[{s.source}]"
                if r < num_rows and c < num_cols:
                    grid[r][c] = t_val
            for row in grid:
                lines.append(" | ".join(row))
            lines.append("")
        else:
            lines.append(translated)
            lines.append("")
            i += 1

    return "\n".join(lines).encode("utf-8"), "text/plain; charset=utf-8"


def _build_docx(segments: List, source_lang: str, target_lang: str) -> tuple[bytes, str]:
    """
    Build a DOCX file preserving headings, lists, tables, and paragraphs in their original order.
    Layout formatting is optimized to avoid unintended blank pages while letting long documents
    flow naturally across pages without shrinking text.
    """
    import docx as docx_module
    from docx.shared import Inches, Pt, RGBColor

    document = docx_module.Document()

    # Apply modest, professional margins (0.65 in top/bottom, 0.75 in left/right)
    for section in document.sections:
        section.top_margin = Inches(0.65)
        section.bottom_margin = Inches(0.65)
        section.left_margin = Inches(0.75)
        section.right_margin = Inches(0.75)
        section.header_distance = Inches(0.4)
        section.footer_distance = Inches(0.4)

    # Clean, compact institutional document header (no artificial blank spacer paragraphs)
    header_para = document.add_paragraph()
    header_para.paragraph_format.space_before = Pt(0)
    header_para.paragraph_format.space_after = Pt(2)
    title_run = header_para.add_run("TRANSLATED DOCUMENT")
    title_run.bold = True
    title_run.font.size = Pt(13)

    sub_para = document.add_paragraph()
    sub_para.paragraph_format.space_before = Pt(0)
    sub_para.paragraph_format.space_after = Pt(8)
    sub_run = sub_para.add_run(
        f"Translated from {source_lang} to {target_lang} · SYNORA IndicTranslate · Machine translation draft (Human review required)"
    )
    sub_run.font.size = Pt(8.5)
    sub_run.italic = True
    sub_run.font.color.rgb = RGBColor(100, 100, 100)

    i = 0
    n = len(segments)
    while i < n:
        seg = segments[i]
        b_type = getattr(seg, "blockType", None) or "paragraph"
        translated = (seg.translated or "").strip()
        review_note = ""
        if not translated:
            translated = seg.source
            if getattr(seg, "reviewFlag", "") in ("unreviewed", "no_model"):
                review_note = " [NOT TRANSLATED — NEEDS REVIEW]"

        if b_type == "heading":
            level = getattr(seg, "blockLevel", None) or 1
            if level < 1:
                level = 1
            elif level > 9:
                level = 9
            h = document.add_heading(level=level)
            h.paragraph_format.space_before = Pt(8) if level == 1 else Pt(6)
            h.paragraph_format.space_after = Pt(3)
            h.paragraph_format.keep_with_next = True
            h.add_run(translated)
            if review_note:
                note = h.add_run(review_note)
                note.italic = True
            i += 1

        elif b_type == "bullet":
            p = document.add_paragraph(style="List Bullet")
            p.paragraph_format.space_before = Pt(0)
            p.paragraph_format.space_after = Pt(2.5)
            p.paragraph_format.line_spacing = 1.15
            p.add_run(translated)
            if review_note:
                note = p.add_run(review_note)
                note.italic = True
            i += 1

        elif b_type == "table_cell":
            tbl_idx = getattr(seg, "tableIndex", None)
            table_segs = []
            while i < n:
                curr_seg = segments[i]
                curr_type = getattr(curr_seg, "blockType", None)
                curr_tbl_idx = getattr(curr_seg, "tableIndex", None)
                if curr_type == "table_cell" and curr_tbl_idx == tbl_idx:
                    table_segs.append(curr_seg)
                    i += 1
                else:
                    break

            num_rows = max((s.rowIndex or 0) for s in table_segs) + 1
            num_cols = max((s.cellIndex or 0) for s in table_segs) + 1
            if getattr(seg, "numRows", None) and seg.numRows > num_rows:
                num_rows = seg.numRows
            if getattr(seg, "numCols", None) and seg.numCols > num_cols:
                num_cols = seg.numCols

            tbl = document.add_table(rows=num_rows, cols=num_cols)
            tbl.style = "Table Grid"

            for s in table_segs:
                r = s.rowIndex if s.rowIndex is not None else 0
                c = s.cellIndex if s.cellIndex is not None else 0
                if r < len(tbl.rows) and c < len(tbl.rows[r].cells):
                    cell_trans = (s.translated or "").strip()
                    cell_note = ""
                    if not cell_trans:
                        cell_trans = s.source
                        if getattr(s, "reviewFlag", "") in ("unreviewed", "no_model"):
                            cell_note = " [NOT TRANSLATED]"
                    cell = tbl.rows[r].cells[c]
                    cell.text = cell_trans
                    for cp in cell.paragraphs:
                        cp.paragraph_format.space_before = Pt(1)
                        cp.paragraph_format.space_after = Pt(1)
                        cp.paragraph_format.line_spacing = 1.05
                    if cell_note:
                        p = cell.paragraphs[0] if cell.paragraphs else cell.add_paragraph()
                        note = p.add_run(cell_note)
                        note.italic = True

            # Note: No empty spacer paragraph added after table; following paragraph naturally spaces

        else:
            # Normal paragraph
            p = document.add_paragraph()
            p.paragraph_format.space_before = Pt(0)
            p.paragraph_format.space_after = Pt(4.5)
            p.paragraph_format.line_spacing = 1.15
            p.add_run(translated)
            if review_note:
                note = p.add_run(review_note)
                note.italic = True
            i += 1

    buf = io.BytesIO()
    document.save(buf)
    buf.seek(0)
    content_type = (
        "application/vnd.openxmlformats-officedocument.wordprocessingml.document"
    )
    return buf.read(), content_type
